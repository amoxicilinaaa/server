function doSetNewAddon(cid,pb,addon,addonlook)
local oldaddon = getItemAttribute(pb, "addonlook")
doSetItemAttribute(pb,"addon",addon)
doSetItemAttribute(pb,"addonlook",addonlook)
local newaddon = getItemAttribute(pb, "addonlook")
 doPlayerSendTextMessage(cid, 27, "Você trocou o addon ("..oldaddon..") pelo addon ("..newaddon..").")
    if #getCreatureSummons(cid) > 0 then
        local pk = getCreatureSummons(cid)[1]
        doSetCreatureOutfit(pk, {lookType = addon}, -1)
          doCreatureSay(cid, getItemAttribute(pb, "poke").." use "..getItemAttribute(pb, "addonlook") ..".", 19)
    end
   
end
 
 
 
 
 
 
function getTotalAddons(pb)
 local totaladdons = 0
      for i = 1, limitaddon do
        local atrib = "addon"..i
        local checked = getItemAttribute(pb, atrib) or 0
        if checked ~= 0 then
            totaladdons = totaladdons+1
        end
      end
    return totaladdons
end